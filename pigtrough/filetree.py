"""An in-memory file tree that is synced to disk with minimal writes.

Rojo watches the output directory and pushes every changed file into Studio,
so we only touch files whose bytes actually changed, write them atomically,
and delete files we generated previously but no longer produce.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

from .rbx import Instance

MANIFEST = ".pigtrough-manifest.json"
SKIP_NAMES = {"__pycache__", ".DS_Store", "Thumbs.db"}


def _clean(path: str) -> str:
    p = PurePosixPath(path.replace("\\", "/"))
    if p.is_absolute() or ".." in p.parts or not p.parts:
        raise ValueError(f"Invalid tree path: {path!r}")
    return str(p)


class FileTree:
    def __init__(self) -> None:
        self.files: dict[str, bytes] = {}

    def add(self, path: str, data: bytes | str, overwrite: bool = False) -> None:
        path = _clean(path)
        if path in self.files and not overwrite:
            raise ValueError(f"Duplicate generated file: {path}")
        self.files[path] = data.encode("utf-8") if isinstance(data, str) else data

    def add_json(self, path: str, obj, overwrite: bool = False) -> None:
        self.add(path, json.dumps(obj, indent=2) + "\n", overwrite)

    def add_model(self, path: str, instance: Instance, overwrite: bool = False) -> None:
        self.add_json(path, instance.to_model_json(root=True), overwrite)

    def add_dir(self, source: Path, dest: str, overwrite: bool = False) -> None:
        for file in sorted(source.rglob("*")):
            if file.is_file() and not SKIP_NAMES.intersection(file.parts):
                rel = file.relative_to(source).as_posix()
                self.add(f"{dest}/{rel}", file.read_bytes(), overwrite)

    def __contains__(self, path: str) -> bool:
        return _clean(path) in self.files

    def __len__(self) -> int:
        return len(self.files)


@dataclass
class SyncResult:
    written: list[str] = field(default_factory=list)
    deleted: list[str] = field(default_factory=list)
    unchanged: int = 0

    def summary(self) -> str:
        return f"{len(self.written)} written, {len(self.deleted)} deleted, {self.unchanged} unchanged"


def sync(tree: FileTree, out_dir: Path, force: bool = False) -> SyncResult:
    out_dir = Path(out_dir)
    manifest_path = out_dir / MANIFEST
    previous: list[str] = []
    if manifest_path.exists():
        previous = json.loads(manifest_path.read_text("utf-8"))
    elif out_dir.exists() and any(out_dir.iterdir()) and not force:
        raise RuntimeError(
            f"{out_dir} is not empty and was not generated by pigtrough; "
            "refusing to write into it (pass --force to override)"
        )

    result = SyncResult()
    for rel, data in sorted(tree.files.items()):
        target = out_dir / rel
        if target.is_file() and target.read_bytes() == data:
            result.unchanged += 1
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp = target.with_name(target.name + ".tmp")
        tmp.write_bytes(data)
        os.replace(tmp, target)
        result.written.append(rel)

    for rel in sorted(set(previous) - set(tree.files)):
        target = out_dir / _clean(rel)
        if target.is_file():
            target.unlink()
            result.deleted.append(rel)
            _prune_empty_dirs(target.parent, out_dir)

    out_dir.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(sorted(tree.files), indent=1) + "\n", "utf-8")
    return result


def _prune_empty_dirs(directory: Path, stop: Path) -> None:
    while directory != stop and directory.is_dir() and not any(directory.iterdir()):
        directory.rmdir()
        directory = directory.parent
